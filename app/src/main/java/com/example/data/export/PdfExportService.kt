                            com.example.ui.localization.AppLanguageSupported.RUSSIAN -> "Сбер."
                            com.example.ui.localization.AppLanguageSupported.ARABIC -> "ادخار"
                            else -> "Épa."
                        }
                        else -> tx.type
                    }

                    // Amounts color theme
                    val txColor = when (tx.type) {
                        "INCOME" -> "#2E7D32"
                        "EXPENSE" -> "#C62828"
                        else -> "#1565C0"
                    }
                    val rowAmountPaint = Paint().apply {
                        color = Color.parseColor(txColor)
                        textSize = 8f
                        typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD)
                        isAntiAlias = true
                    }

                    val rowNormalPaint = Paint().apply {
                        color = Color.parseColor("#424242")
                        textSize = 8f
                        isAntiAlias = true
                    }

                    // Category & description wrapping limits
                    val catText = truncateTextToWidth(categoryDisplay, 120f, rowNormalPaint)
                    val labelText = truncateTextToWidth(tx.label, 160f, rowNormalPaint)

                    cursor.canvas?.drawText(formattedDate, colDateX, cursor.currentY, rowNormalPaint)
                    cursor.canvas?.drawText(txType, colTypeX, cursor.currentY, rowNormalPaint)
                    cursor.canvas?.drawText(catText, colCatX, cursor.currentY, rowNormalPaint)
                    cursor.canvas?.drawText(labelText, colLabelX, cursor.currentY, rowNormalPaint)

                    val amtWidth = rowAmountPaint.measureText(formattedAmt)
                    cursor.canvas?.drawText(formattedAmt, colAmountX - amtWidth, cursor.currentY, rowAmountPaint)
                    
                    // Tiny bottom line separator between rows
                    val rowUnderlinePaint = Paint().apply {
                        color = Color.parseColor("#EEEEEE")
                        strokeWidth = 0.5f
                        style = Paint.Style.STROKE
                    }
                    cursor.canvas?.drawLine(cursor.margin, cursor.currentY + 3f, cursor.width - cursor.margin, cursor.currentY + 3f, rowUnderlinePaint)

                    cursor.moveDown(14f)
                }
            }

            cursor.finish()

            // Save inside context cache folder or cache system
            val cacheDir = context.cacheDir
            val joyReportDir = File(cacheDir, "joy_reports").apply { mkdirs() }
            val formattedDateName = SimpleDateFormat("yyyy-MM", Locale.getDefault()).format(Date())
            val pdfFile = File(joyReportDir, "budget-joy-$formattedDateName.pdf")

            val outStream = FileOutputStream(pdfFile)
            pdfDocument.writeTo(outStream)
            outStream.flush()
            outStream.close()

            Log.d(tag, "Successfully created budget report PDF at: ${pdfFile.absolutePath}")
            return pdfFile
        } catch (e: Exception) {
            Log.e(tag, "Fail during PDF formatting generation", e)
            return null
        } finally {
            pdfDocument.close()
        }
    }

    /**
     * Splits paragraph text in small pieces to support wrap block printing.
     */
    private fun drawMultilineText(
        text: String,
        x: Float,
        widthLimit: Float,
        paint: Paint,
        cursor: PageCursor,
        lineSpacing: Float = 11f
    ) {
        val words = text.split(" ")
        var currentLine = StringBuilder()
        for (word in words) {
            val testLine = if (currentLine.isEmpty()) word else "${currentLine} $word"
            val testWidth = paint.measureText(testLine)
            if (testWidth > widthLimit) {
                cursor.ensureSpace(lineSpacing)
                cursor.canvas?.drawText(currentLine.toString(), x, cursor.currentY, paint)
                cursor.moveDown(lineSpacing)
                currentLine = StringBuilder(word)
            } else {
                currentLine = StringBuilder(testLine)
            }
        }
        if (currentLine.isNotEmpty()) {
            cursor.ensureSpace(lineSpacing)
            cursor.canvas?.drawText(currentLine.toString(), x, cursor.currentY, paint)
            cursor.moveDown(lineSpacing)
        }
    }

    /**
     * Helps truncate text exactly matching limits.
     */
    private fun truncateTextToWidth(text: String, widthLimit: Float, paint: Paint): String {
        val ellipsis = "..."
        if (paint.measureText(text) <= widthLimit) return text
        var truncated = text
        while (truncated.isNotEmpty() && paint.measureText("$truncated$ellipsis") > widthLimit) {
            truncated = truncated.dropLast(1)
        }
        return if (truncated.isEmpty()) ellipsis else "$truncated$ellipsis"
    }
