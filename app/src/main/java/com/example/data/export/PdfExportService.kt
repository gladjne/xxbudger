class PdfExportService {
    private val tag = "PdfExportService"

    // PageCursor tracks dynamic vertical layout and handles auto-generation of pages.
    private class PageCursor(
        private val pdfDocument: PdfDocument,
        val width: Int = 595, // A4 standard width at 72dpi
        val height: Int = 842, // A4 standard height at 72dpi
        val margin: Float = 40f,
        val lang: com.example.ui.localization.AppLanguageSupported = com.example.presentation.ui.UiUtils.currentLanguage
    ) {
        var pageNumber = 1
            private set
        var currentPage: PdfDocument.Page? = null
            private set
        var canvas: Canvas? = null
            private set
        var currentY = margin
            private set

        init {
            startNewPage()
        }

        fun startNewPage() {
            if (currentPage != null) {
                drawFooter()
                pdfDocument.finishPage(currentPage)
            }
            val pageInfo = PdfDocument.PageInfo.Builder(width, height, pageNumber).create()
            currentPage = pdfDocument.startPage(pageInfo)
            canvas = currentPage!!.canvas
            currentY = margin
            drawHeader()
            pageNumber++
        }

        private fun drawHeader() {
            val c = canvas ?: return
            if (pageNumber > 1) {
                // Subtle gray lines on follow-up pages
                val p = Paint().apply {
                    color = Color.parseColor("#E0E0E0")
                    strokeWidth = 1f
                    style = Paint.Style.STROKE
                }
                c.drawLine(margin, margin - 10f, width - margin, margin - 10f, p)

                val textPaint = Paint().apply {
                    color = Color.parseColor("#757575")
                    textSize = 8f
                    isAntiAlias = true
                    typeface = Typeface.create(Typeface.DEFAULT, Typeface.ITALIC)
                }
                val headerText = when (lang) {
                    com.example.ui.localization.AppLanguageSupported.ENGLISH -> "Budget Joy Report (continued)"
                    com.example.ui.localization.AppLanguageSupported.DEUTSCH -> "Budget Joy Bericht (Fortsetzung)"
                    com.example.ui.localization.AppLanguageSupported.ESPANOL -> "Informe Budget Joy (continuación)"
                    com.example.ui.localization.AppLanguageSupported.ITALIANO -> "Rapporto Budget Joy (continua)"
                    com.example.ui.localization.AppLanguageSupported.PORTUGUES -> "Relatório Budget Joy (continuação)"
                    com.example.ui.localization.AppLanguageSupported.CHINESE -> "Budget Joy 报告 (续)"
                    com.example.ui.localization.AppLanguageSupported.JAPANESE -> "Budget Joy レポート (続き)"
                    com.example.ui.localization.AppLanguageSupported.KOREAN -> "Budget Joy 보고서 (계속)"
                    com.example.ui.localization.AppLanguageSupported.RUSSIAN -> "Отчет Budget Joy (продолжение)"
                    com.example.ui.localization.AppLanguageSupported.ARABIC -> "تقرير Budget Joy (متابع)"
                    else -> "Rapport Budget Joy (suite)"
                }
                c.drawText(headerText, margin, margin - 15f, textPaint)
                currentY = margin + 10f
            }
        }

        private fun drawFooter() {
            val c = canvas ?: return
            val p = Paint().apply {
                color = Color.parseColor("#E0E0E0")
                strokeWidth = 1f
                style = Paint.Style.STROKE
            }
            c.drawLine(margin, height - margin + 10f, width - margin, height - margin + 10f, p)

            val textPaint = Paint().apply {
                color = Color.parseColor("#757575")
                textSize = 8f
                isAntiAlias = true
            }
            val footerText = when (lang) {
                com.example.ui.localization.AppLanguageSupported.ENGLISH -> "Generated by Budget Joy"
                com.example.ui.localization.AppLanguageSupported.DEUTSCH -> "Generiert von Budget Joy"
                com.example.ui.localization.AppLanguageSupported.ESPANOL -> "Generado por Budget Joy"
                com.example.ui.localization.AppLanguageSupported.ITALIANO -> "Generato da Budget Joy"
                com.example.ui.localization.AppLanguageSupported.PORTUGUES -> "Gerado por Budget Joy"
                com.example.ui.localization.AppLanguageSupported.CHINESE -> "由 Budget Joy 生成"
                com.example.ui.localization.AppLanguageSupported.JAPANESE -> "Budget Joy によって生成"
                com.example.ui.localization.AppLanguageSupported.KOREAN -> "Budget Joy에 의해 생성됨"
                com.example.ui.localization.AppLanguageSupported.RUSSIAN -> "Создано в Budget Joy"
                com.example.ui.localization.AppLanguageSupported.ARABIC -> "تم الإنشاء بواسطة Budget Joy"
                else -> "Généré par Budget Joy"
            }
            c.drawText(footerText, margin, height - margin + 22f, textPaint)

            val pageLabel = when (lang) {
                com.example.ui.localization.AppLanguageSupported.ENGLISH -> "Page"
                com.example.ui.localization.AppLanguageSupported.DEUTSCH -> "Seite"
                com.example.ui.localization.AppLanguageSupported.ESPANOL -> "Página"
                com.example.ui.localization.AppLanguageSupported.ITALIANO -> "Pagina"
                com.example.ui.localization.AppLanguageSupported.PORTUGUES -> "Página"
                com.example.ui.localization.AppLanguageSupported.CHINESE -> "页"
                com.example.ui.localization.AppLanguageSupported.JAPANESE -> "ページ"
                com.example.ui.localization.AppLanguageSupported.KOREAN -> "페이지"
                com.example.ui.localization.AppLanguageSupported.RUSSIAN -> "Страница"
                com.example.ui.localization.AppLanguageSupported.ARABIC -> "صفحة"
                else -> "Page"
            }
            val pageStr = "$pageLabel ${pageNumber - 1}"
            val bounds = Rect()
            textPaint.getTextBounds(pageStr, 0, pageStr.length, bounds)
            c.drawText(pageStr, width - margin - bounds.width(), height - margin + 22f, textPaint)
        }

        fun ensureSpace(heightNeeded: Float) {
            if (currentY + heightNeeded > height - margin) {
                startNewPage()
            }
        }

        fun moveDown(dy: Float) {
            currentY += dy
        }

        fun finish() {
            if (currentPage != null) {
                drawFooter()
                pdfDocument.finishPage(currentPage)
                currentPage = null
                canvas = null
            }
        }
    }

