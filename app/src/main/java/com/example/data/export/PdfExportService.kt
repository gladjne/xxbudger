            }
            cursor.moveDown(10f)

            // Divider line
            cursor.canvas?.drawLine(cursor.margin, cursor.currentY, cursor.width - cursor.margin, cursor.currentY, linePaint)
            cursor.moveDown(15f)

            // --- SECTION 1: FINANCIAL SUMMARY ---
            cursor.ensureSpace(90f)
            val secFinSummary = when (lang) {
                com.example.ui.localization.AppLanguageSupported.ENGLISH -> "MONTHLY FINANCIAL OVERVIEW"
                com.example.ui.localization.AppLanguageSupported.DEUTSCH -> "FINANZÜBERSICHT DES MONATS"
                com.example.ui.localization.AppLanguageSupported.ESPANOL -> "RESUMEN FINANCIERO MENSUAL"
                com.example.ui.localization.AppLanguageSupported.ITALIANO -> "RIEPILOGO FINANZIARIO MENSILE"
